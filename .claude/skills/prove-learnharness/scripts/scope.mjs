#!/usr/bin/env node
/**
 * scope.mjs [--base <ref>] [--files a,b,c] [--json]
 *
 * Works out from the diff which surfaces and tiers a change reaches, and the
 * scripted checks to run, so a prove run drives only what the change touches.
 * Diff = uncommitted work plus commits since merge-base(HEAD, base ref)
 * (default $PROVE_BASE_REF or origin/main), plus untracked files.
 * --files skips git and scopes the given paths (for a dry run).
 *
 * This is the Scope map of SKILL.md as code. When a rule here and the table
 * in SKILL.md disagree, fix both in the same change.
 */
import { execFileSync } from "node:child_process";
import * as path from "node:path";

const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };
const repo = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: import.meta.dirname, encoding: "utf8" }).trim();
const git = (...a) => execFileSync("git", a, { cwd: repo, encoding: "utf8" }).trim();
const baseRef = opt("base") ?? process.env.PROVE_BASE_REF ?? "origin/main";

let base = "n/a", head = "n/a", files;
if (opt("files")) files = opt("files").split(",").filter(Boolean);
else {
	base = git("merge-base", "HEAD", baseRef);
	head = git("rev-parse", "HEAD");
	const changed = git("diff", "--name-only", base).split("\n").filter(Boolean);
	const untracked = git("ls-files", "--others", "--exclude-standard").split("\n").filter(Boolean);
	files = [...new Set([...changed, ...untracked])].sort();
}

// Rules, first match wins. surfaces: web, api, agent, selfhost-a, selfhost-b,
// electron-dev, electron-packaged, mobile, ci-script, ci-tests, protocol (planned).
const ALL = ["web", "api", "selfhost-a", "electron-dev"];
const RULES = [
	[/^\.claude\/|^\.prove-it\/snapshots\//, [], "prove skill or its answer keys: no app surface"],
	[/^(docs\/|examples\/|skills\/|LICENSE|README\.md|CONTRIBUTING\.md|SECURITY\.md|AGENTS\.md|CLAUDE\.md)/, [], "docs: no app surface"],
	[/^(tests\/|selfhost\/tests\/)/, [], "tests only: no app surface"],
	[/^eslint\.config\.mjs$/, [], "lint configuration"],
	[/^\.github\/scripts\/.*\.test\.cjs$/, ["ci-tests"], "CI script tests only: run them"],
	[/^\.github\/scripts\//, ["ci-script"], "CI or release script: its own tests, then its CLI driven with fixtures written from its spec (see SKILL.md Scope)"],
	[/^\.github\//, [], "CI config: no app surface (CI itself proves it)"],
	[/^(\.gitignore|\.gitattributes|next-env\.d\.ts)$/, [], "repo housekeeping or generated by next build: no app surface"],
	[/^apps\/mobile\//, ["mobile"], "Expo beta (see references/features/mobile-beta.md)"],
	[/^app\/api\/v\d+\//, ["protocol", "api"], "PLANNED surface: versioned client protocol (see references/planned.md)"],
	[/^src\/client-protocol\/|^app\/\.well-known\//, ["api", "web", "agent", "mobile"], "client protocol contract and server info (docs/specs/client-protocol.md): the types the protocol 1 routes satisfy and the constants proxy.ts reads"],
	[/^app\/api\/(updates|health)\/|^src\/server\/self-update\.ts$/, ["api", "selfhost-a", "selfhost-b", "web"], "server half of self-update"],
	[/^app\/api\/(chat|chats|practice)\//, ["api", "web", "agent", "mobile"], "turn and session routes"],
	[/^app\/api\//, ["api", "web"], "API route"],
	[/^(app|components|public)\//, ["web"], "web UI"],
	[/^lib\//, ["web", "api"], "shared client/server helper"],
	[/^src\/agent\/(tools|subagents|prompts)\/|^src\/agent\/[^/]+\.(ts|md)$/, ["agent", "web", "api"], "agent loop, tools or prompts"],
	[/^src\/agent\//, ["agent", "web", "api"], "agent provider code"],
	[/^src\/(core|server|store)\//, ["web", "api", "agent"], "shared core/server/store code"],
	[/^selfhost\/(src\/(supervisor|release|backup|service|protocol|server|locks|versions)\.ts|lh\.ts|install\.sh|lh\.sh|scripts\/package-archive\.ts)$/, ["selfhost-a", "selfhost-b"], "launcher update/rollback/install path"],
	[/^selfhost\//, ["selfhost-a"], "launcher"],
	[/^electron\/(main|preload|desktop-api)\.cjs$|^electron-builder\.yml$|^scripts\/(after-pack\.cjs|build-server\.mjs)$/, ["electron-dev", "electron-packaged", "web"], "desktop shell spawn, bridge or packaging"],
	[/^electron\//, ["electron-dev"], "desktop shell"],
	[/^plugins\/|^core-plugins\.json$|^scripts\/(build-core-plugins|setup-plugins|build-plugin-\w+)\.mjs$/, ["web", "api", "agent"], "plugins"],
	[/^(package\.json|package-lock\.json|next\.config\.ts|proxy\.ts|instrumentation\.ts|config\.ts|tsconfig\.json|postcss\.config\.mjs|components\.json)$/, [...ALL, "agent"], "launch config: smoke every surface"],
	[/^scripts\/smoke-|^scripts\/lib\//, [], "release smoke gate: run that script itself"],
	[/^scripts\//, [], "dev script: no app surface unless the change says so"],
];

const surfaces = {};
const reasons = [];
const unmapped = [];
for (const file of files) {
	const rule = RULES.find(([re]) => re.test(file));
	if (!rule) { unmapped.push(file); continue; }
	const [, reach, why] = rule;
	reasons.push(`${file} -> ${reach.length ? reach.join(", ") : "none"} (${why})`);
	for (const s of reach) (surfaces[s] ??= []).push(file);
}
// A change whose every file is new still gets one smoke of the main flow.
const allNew = !opt("files") && files.length > 0 && files.every((f) => { try { execFileSync("git", ["cat-file", "-e", `${base}:${f}`], { cwd: repo, stdio: "ignore" }); return false; } catch { return true; } });
const reached = Object.keys(surfaces);
const appSurface = (s) => s !== "ci-script" && s !== "ci-tests";
if (allNew && reached.some(appSurface) && !reached.includes("web")) surfaces.web = ["(smoke: change is only new files)"];

const needsBase = Object.keys(surfaces).some((s) => ["web", "api", "agent", "selfhost-a", "selfhost-b"].includes(s));
const plan = [];
if (Object.keys(surfaces).length) {
	const web = surfaces.web || surfaces.agent;
	const api = surfaces.api || surfaces.agent;
	const electron = surfaces["electron-packaged"] ? "packaged" : surfaces["electron-dev"] ? "dev" : null;
	const allow = `--allow 'apiCalls=GET /api/updates 200' --allow 'apiCalls=GET /api/subscriptions 200'`;
	plan.push(`RUN=$(scripts/new-run.sh <slug>)`);
	plan.push(`node scripts/scope.mjs > "$RUN/scope.txt"`);
	if (Object.keys(surfaces).some(appSurface)) plan.push(`scripts/build.sh "$RUN" ${needsBase || surfaces["selfhost-b"] ? "both" : "head"}`);
	if (surfaces["ci-script"] || surfaces["ci-tests"]) plan.push(`(cd "$(git rev-parse --show-toplevel)" && node --test .github/scripts/*.test.cjs)   # the CI scripts' own tests`);
	// A changed script (not only its tests) is a CLI to drive by hand.
	if (surfaces["ci-script"]) plan.push("# MANUAL: drive each changed .github/scripts CLI with fixtures you write from its spec (not from the script), and each workflow step that calls it against stubs.");
	if ((web || api) && needsBase) {
		plan.push(`H=$(scripts/start.sh "$RUN" head); B=$(scripts/start.sh "$RUN" base); scripts/health.sh "$H"; scripts/health.sh "$B"`);
	} else if (electron) {
		plan.push(`H=$(scripts/start.sh "$RUN" head); scripts/health.sh "$H"`);
	}
	if (web) {
		plan.push("scripts/ensure-axe.sh");
		plan.push(`node scripts/web-teach.mjs "$B"; node scripts/web-teach.mjs "$H"`);
		plan.push(`node scripts/compare.mjs "$RUN/base/web-teach/result.json" "$RUN/head/web-teach/result.json" --out "$RUN/compare-web.md"`);
		plan.push(`node scripts/probes.mjs "$B"; node scripts/probes.mjs "$H"; node scripts/compare.mjs "$RUN/base/probes/result.json" "$RUN/head/probes/result.json" --out "$RUN/compare-probes.md"`);
	}
	if (api) plan.push(`node scripts/api-check.mjs "$B"; node scripts/api-check.mjs "$H"; node scripts/compare.mjs "$RUN/base/api-check/result.json" "$RUN/head/api-check/result.json" --out "$RUN/compare-api.md"`);
	if (surfaces["selfhost-a"]) plan.push(`scripts/selfhost-a.sh "$RUN" base; scripts/selfhost-a.sh "$RUN" head; node scripts/compare.mjs "$RUN/base/selfhost-a/result.json" "$RUN/head/selfhost-a/result.json" --out "$RUN/compare-selfhost-a.md"`);
	if (surfaces["selfhost-b"]) plan.push(`scripts/selfhost-b.sh "$RUN"`);
	if (electron) {
		if (!web) plan.push(`node scripts/web-teach.mjs "$H"`);
		plan.push(`E=$(scripts/electron.sh "$RUN" ${electron}); node scripts/web-teach.mjs "$E"; node scripts/compare.mjs "$RUN/head/web-teach/result.json" "$RUN/electron-${electron}/web-teach/result.json" ${allow} --out "$RUN/compare-electron.md"`);
	}
	if (surfaces.mobile) plan.push("# MANUAL: device proof next: in a new run folder (scripts/new-run.sh <slug>-device), drive references/features/mobile-beta.md, emulator health gate first, and name both run folders in one receipt. The iOS variant: references/planned.md (iOS).");
	if (surfaces.protocol) plan.push("# PLANNED versioned protocol surface: see references/planned.md.");
	plan.push(`scripts/stop.sh "$RUN"`);
}

const out = { baseRef, base, head, files, surfaces, unmapped, reasons, plan };
if (args.includes("--json")) { console.log(JSON.stringify(out, null, 2)); process.exit(0); }
console.log(`base ${base.slice(0, 12)} (${baseRef}) .. head ${head.slice(0, 12)}: ${files.length} files changed since the merge-base (committed, uncommitted and untracked)`);
for (const r of reasons) console.log(`  ${r}`);
for (const u of unmapped) console.log(`  ${u} -> UNMAPPED: decide by hand and add a rule here and in SKILL.md`);
console.log(`surfaces: ${Object.keys(surfaces).join(", ") || "none (no app surface: say so in the receipt and stop)"}`);
if (plan.length) {
	console.log("plan (run from the skill folder; or all of it: scripts/run-plan.sh <slug> with the same arguments as this scope.mjs call):");
	for (const p of plan) console.log(`  ${p}`);
}
