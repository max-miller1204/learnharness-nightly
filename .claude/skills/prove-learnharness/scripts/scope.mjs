#!/usr/bin/env node
/**
 * scope.mjs [--base <ref>] [--files a,b,c] [--json]
 *
 * Works out from the diff which surfaces and tiers a change reaches, and the
 * scripted checks to run, so a prove run drives only what the change touches.
 * Diff = uncommitted work plus commits since merge-base(HEAD, base ref)
 * (default $PROVE_BASE_REF or origin/main), plus untracked files.
 * --files skips git and scopes the given paths (for a dry run).
 *
 * This is the Scope map of SKILL.md as code. When a rule here and the table
 * in SKILL.md disagree, fix both in the same change.
 */
import { execFileSync } from "node:child_process";
import * as path from "node:path";

const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };
const repo = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: import.meta.dirname, encoding: "utf8" }).trim();
const git = (...a) => execFileSync("git", a, { cwd: repo, encoding: "utf8" }).trim();
const baseRef = opt("base") ?? process.env.PROVE_BASE_REF ?? "origin/main";

let base = "n/a", head = "n/a", files;
if (opt("files")) files = opt("files").split(",").filter(Boolean);
else {
	base = git("merge-base", "HEAD", baseRef);
	head = git("rev-parse", "HEAD");
	const changed = git("diff", "--name-only", base).split("\n").filter(Boolean);
	const untracked = git("ls-files", "--others", "--exclude-standard").split("\n").filter(Boolean);
	files = [...new Set([...changed, ...untracked])].sort();
}

// Rules, first match wins. surfaces: web, api, agent, selfhost-a, selfhost-b,
// electron-dev, electron-packaged, mobile (planned), protocol (planned).
// hard: true marks shared or edge-of-competence code (see Sort the change).
const ALL = ["web", "api", "selfhost-a", "electron-dev"];
const RULES = [
	[/^\.claude\/|^\.prove-it\/snapshots\//, [], false, "prove skill or its answer keys: no app surface"],
	[/^(docs\/|examples\/|skills\/|LICENSE|README\.md|CONTRIBUTING\.md|SECURITY\.md|AGENTS\.md|CLAUDE\.md)/, [], false, "docs: no app surface"],
	[/^(tests\/|selfhost\/tests\/)/, [], false, "tests only: no app surface"],
	[/^\.github\//, [], false, "CI config: no app surface (CI itself proves it)"],
	[/^(\.gitignore|\.gitattributes|next-env\.d\.ts)$/, [], false, "repo housekeeping or generated by next build: no app surface"],
	[/^(apps\/mobile|mobile)\//, ["mobile"], true, "PLANNED surface: Expo app (see references/planned.md)"],
	[/^app\/api\/v\d+\//, ["protocol", "api"], true, "PLANNED surface: versioned client protocol (see references/planned.md)"],
	[/^app\/api\/(updates|health)\/|^src\/server\/self-update\.ts$/, ["api", "selfhost-a", "selfhost-b", "web"], true, "server half of self-update"],
	[/^app\/api\/(chat|chats)\//, ["api", "web", "agent"], true, "turn and session routes"],
	[/^app\/api\//, ["api", "web"], false, "API route"],
	[/^(app|components|public)\//, ["web"], false, "web UI"],
	[/^lib\//, ["web", "api"], true, "shared client/server helper"],
	[/^src\/agent\/(tools|subagents|prompts)\/|^src\/agent\/[^/]+\.(ts|md)$/, ["agent", "web", "api"], true, "agent loop, tools or prompts"],
	[/^src\/agent\//, ["agent", "web", "api"], true, "agent provider code"],
	[/^src\/(core|server|store)\//, ["web", "api", "agent"], true, "shared core/server/store code"],
	[/^selfhost\/(src\/(supervisor|release|backup|service|protocol|server|locks|versions)\.ts|lh\.ts|install\.sh|lh\.sh|scripts\/package-archive\.ts)$/, ["selfhost-a", "selfhost-b"], true, "launcher update/rollback/install path"],
	[/^selfhost\//, ["selfhost-a"], false, "launcher"],
	[/^electron\/(main|preload|desktop-api)\.cjs$|^electron-builder\.yml$|^scripts\/(after-pack\.cjs|build-server\.mjs)$/, ["electron-dev", "electron-packaged", "web"], true, "desktop shell spawn, bridge or packaging"],
	[/^electron\//, ["electron-dev"], false, "desktop shell"],
	[/^plugins\/|^core-plugins\.json$|^scripts\/(build-core-plugins|setup-plugins|build-plugin-\w+)\.mjs$/, ["web", "api", "agent"], true, "plugins"],
	[/^(package\.json|package-lock\.json|next\.config\.ts|proxy\.ts|instrumentation\.ts|config\.ts|tsconfig\.json|postcss\.config\.mjs|components\.json)$/, [...ALL, "agent"], true, "launch config: smoke every surface"],
	[/^scripts\/smoke-|^scripts\/lib\//, [], false, "release smoke gate: run that script itself"],
	[/^scripts\//, [], false, "dev script: no app surface unless the change says so"],
];

const surfaces = {};
const reasons = [];
const unmapped = [];
let hard = false;
for (const file of files) {
	const rule = RULES.find(([re]) => re.test(file));
	if (!rule) { unmapped.push(file); continue; }
	const [, reach, isHard, why] = rule;
	if (isHard && reach.length) hard = true;
	reasons.push(`${file} -> ${reach.length ? reach.join(", ") : "none"} (${why}${isHard && reach.length ? ", hard" : ""})`);
	for (const s of reach) (surfaces[s] ??= []).push(file);
}
// A change whose every file is new still gets one smoke of the main flow.
const allNew = !opt("files") && files.length > 0 && files.every((f) => { try { execFileSync("git", ["cat-file", "-e", `${base}:${f}`], { cwd: repo, stdio: "ignore" }); return false; } catch { return true; } });
const reached = Object.keys(surfaces);
if (allNew && reached.length && !reached.includes("web")) surfaces.web = ["(smoke: change is only new files)"];

const needsBase = Object.keys(surfaces).some((s) => ["web", "api", "agent", "selfhost-a", "selfhost-b"].includes(s));
const plan = [];
if (Object.keys(surfaces).length) {
	plan.push(`RUN=$(scripts/new-run.sh <slug>)`);
	plan.push(needsBase || surfaces["selfhost-b"] ? `scripts/build.sh "$RUN" both` : `scripts/build.sh "$RUN" head`);
	if (surfaces.web || surfaces.api || surfaces.agent || surfaces["electron-dev"] || surfaces["electron-packaged"]) {
		plan.push(`H=$(scripts/start.sh "$RUN" head); B=$(scripts/start.sh "$RUN" base); scripts/health.sh "$H"; scripts/health.sh "$B"`);
	}
	if (surfaces.web || surfaces.agent) plan.push(`scripts/ensure-axe.sh; node scripts/web-teach.mjs "$B"; node scripts/web-teach.mjs "$H"; node scripts/compare.mjs "$RUN/base/web-teach/result.json" "$RUN/head/web-teach/result.json" --out "$RUN/compare-web.md"`);
	if (surfaces.api || surfaces.agent) plan.push(`node scripts/api-check.mjs "$B"; node scripts/api-check.mjs "$H"; node scripts/compare.mjs "$RUN/base/api-check/result.json" "$RUN/head/api-check/result.json" --out "$RUN/compare-api.md"`);
	if (surfaces["selfhost-a"]) plan.push(`scripts/selfhost-a.sh "$RUN" base; scripts/selfhost-a.sh "$RUN" head; node scripts/compare.mjs "$RUN/base/selfhost-a/result.json" "$RUN/head/selfhost-a/result.json" --out "$RUN/compare-selfhost-a.md"`);
	if (surfaces["selfhost-b"]) plan.push(`scripts/selfhost-b.sh "$RUN"`);
	if (surfaces["electron-dev"] && !surfaces["electron-packaged"]) plan.push(`E=$(scripts/electron.sh "$RUN" dev); node scripts/web-teach.mjs "$E"; node scripts/compare.mjs "$RUN/head/web-teach/result.json" "$RUN/electron-dev/web-teach/result.json" --allow 'apiCalls=GET /api/updates 200' --allow 'apiCalls=GET /api/subscriptions 200' --out "$RUN/compare-electron.md"`);
	if (surfaces["electron-packaged"]) plan.push(`E=$(scripts/electron.sh "$RUN" packaged); node scripts/web-teach.mjs "$E"; node scripts/compare.mjs "$RUN/head/web-teach/result.json" "$RUN/electron-packaged/web-teach/result.json" --allow 'apiCalls=GET /api/updates 200' --allow 'apiCalls=GET /api/subscriptions 200' --out "$RUN/compare-electron.md"`);
	if (surfaces.mobile || surfaces.protocol) plan.push(`# PLANNED surface reached (${["mobile", "protocol"].filter((s) => surfaces[s]).join(", ")}): no scripts yet. BLOCKED until its section in references/planned.md is built with /prove-it.`);
	plan.push(`scripts/stop.sh "$RUN"`);
}

const out = { baseRef, base, head, files, surfaces, hard, unmapped, reasons, plan };
if (args.includes("--json")) { console.log(JSON.stringify(out, null, 2)); process.exit(0); }
console.log(`base ${base.slice(0, 12)} (${baseRef}) .. head ${head.slice(0, 12)} + uncommitted/untracked: ${files.length} files`);
for (const r of reasons) console.log(`  ${r}`);
for (const u of unmapped) console.log(`  ${u} -> UNMAPPED: decide by hand and add a rule here and in SKILL.md`);
console.log(`surfaces: ${Object.keys(surfaces).join(", ") || "none (no app surface: say so in the receipt and stop)"}`);
console.log(`hard: ${hard ? "yes (full proof in a fresh checker, plus break-it probes)" : "no (scripted checks; a fresh checker only if a script fails)"}`);
if (plan.length) { console.log("plan (run from the skill folder):"); for (const p of plan) console.log(`  ${p}`); }
